"""Every product's mesh policies as one Kustomize bundle, for the data planes' Flux to apply.

`python -m platform_security bundle products -o out` writes `<product>.yaml` per product spec and a
`kustomization.yaml` listing them. The `mesh` workflow publishes the bundle to the `mesh-policies`
branch after every merge to main, and Flux in each data plane applies that branch
(platform-foundation: the `product-mesh` Kustomization). `example.yaml` is documentation, not a
product, so it's left out.

A product's namespace is never deleted by Flux (prune disabled on Namespaces): dropping a spec
removes its policies, not the product's workloads.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from . import mesh, spec

EXAMPLES = {"example.yaml"}


def build(products: str | Path, out: str | Path) -> list[str]:
    """Writes the bundle; returns the products in it, in name order. Raises spec.SpecError on the
    first invalid spec, so a broken spec never publishes half a bundle."""
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    names: list[str] = []
    for path in sorted(Path(products).glob("*.yaml")):
        if path.name in EXAMPLES:
            continue
        s = spec.load(path)
        (out / f"{s['product']}.yaml").write_text(mesh.dump(mesh.render(s)))
        names.append(s["product"])
    kustomization = {
        "apiVersion": "kustomize.config.k8s.io/v1beta1",
        "kind": "Kustomization",
        "resources": [f"{n}.yaml" for n in names],
        "patches": [
            {
                "target": {"kind": "Namespace"},
                "patch": yaml.safe_dump(
                    [
                        {
                            "op": "add",
                            "path": "/metadata/annotations",
                            "value": {"kustomize.toolkit.fluxcd.io/prune": "disabled"},
                        }
                    ]
                ),
            }
        ],
    }
    (out / "kustomization.yaml").write_text(
        "# Generated by `python -m platform_security bundle` from products/*.yaml; don't edit.\n"
        + yaml.safe_dump(kustomization, sort_keys=False)
    )
    return names
